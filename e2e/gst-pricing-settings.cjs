// Localhost-only GST/default pricing acceptance. Coordinator supplies and removes this fixture.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const origin = process.env.STORELY_WEB_ORIGIN || 'http://127.0.0.1:5173'
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw new Error('Localhost origin required')
if (!process.env.STORELY_FIXTURE) throw new Error('Run-owned STORELY_FIXTURE required')
const fixture = JSON.parse(fs.readFileSync(process.env.STORELY_FIXTURE, 'utf8'))
;(async () => {
  const browser = await chromium.launch({ ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) })
  const context = await browser.newContext({ ignoreHTTPSErrors: true })
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  try {
    const login = await context.request.post(origin + '/v1/auth/login', { data: { email: fixture.email, password: fixture.password, client: 'mobile' }, headers: { 'X-Requested-With': 'storely-web' } })
    assert.ok(login.ok(), 'Fixture authentication')
    const headers = { authorization: `Bearer ${(await login.json()).access_token}` }
    const path = `/v1/shops/${fixture.shop_id}/invoice-settings`
    const current = await context.request.get(origin + path, { headers })
    assert.ok(current.ok())
    const original = await current.json()
    // Deterministic initial defaults also make reruns meaningful; mutate only the supplied fixture.
    const initial = await context.request.patch(origin + path, { headers, data: { expected_revision: original.revision, gst_scheme: 'unregistered', default_gst_percent: '18', default_profit_margin_percent: '0', default_overhead_cost: '0' } })
    assert.ok(initial.ok(), 'Initialize disposable fixture defaults')
    const writes = []
    page.on('request', request => { if (request.method() === 'PATCH' && new URL(request.url()).pathname === path) writes.push(request.postDataJSON()) })
    await page.goto(origin + '/settings?tab=pricing')
    await page.getByLabel('Email', { exact: true }).fill(fixture.email)
    await page.getByLabel('Password', { exact: true }).fill(fixture.password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('tab', { name: 'Pricing & tax', exact: true }).click()
    const gst = page.getByLabel('Default GST %', { exact: true })
    const margin = page.getByLabel('Default profit margin %', { exact: true })
    const overhead = page.getByLabel('Default overhead cost (₹)', { exact: true })
    const save = page.getByRole('button', { name: 'Save settings', exact: true })
    await gst.fill('7')
    await margin.fill('12.3456')
    await overhead.fill('0.001')
    await page.getByRole('tab', { name: 'Invoice appearance', exact: true }).click()
    await save.click()
    await page.waitForFunction(() => document.getElementById('tab-pricing')?.getAttribute('aria-selected') === 'true' && document.querySelectorAll('[aria-invalid="true"]').length >= 3)
    assert.equal(await gst.inputValue(), '7')
    assert.equal(await margin.inputValue(), '12.3456')
    assert.equal(await overhead.inputValue(), '0.001')
    assert.equal(writes.length, 0, 'Invalid edited defaults send no PATCH')
    assert.equal(await gst.evaluate(element => document.activeElement === element), true, 'Focus visible invalid GST field')
    await gst.fill('18')
    await margin.fill('12.345')
    await overhead.fill('10')
    await page.getByLabel(/Regular GST/).check()
    async function saveSettings() {
      const response = page.waitForResponse(response => response.request().method() === 'PATCH' && new URL(response.url()).pathname === path)
      await save.click()
      const saved = await response
      assert.ok(saved.ok(), 'Guarded defaults save')
      await page.getByText(/Saved. Phones get the new layout/).waitFor()
      return saved.json()
    }
    const regular = await saveSettings()
    assert.equal(regular.default_profit_margin_percent, '12.345', 'No margin rounding at settings boundary')
    assert.equal(writes[0].default_profit_margin_percent, '12.345')
    assert.match(writes[0].expected_revision, /^s1:\d+$/)
    async function preview(expected, registered) {
      const response = await context.request.post(`${origin}/v1/shops/${fixture.shop_id}/products/price-preview`, { headers, data: { price_mode: 'formula', purchase_price: '1000', selling_price: null, category_uuid: null, gst_percent: null, overhead_cost: null, profit_margin_percent: null } })
      assert.ok(response.ok(), 'Authoritative formula preview')
      const price = await response.json()
      assert.equal(price.selling_price, expected)
      assert.equal(price.profit_margin_percent, '12.345')
      assert.equal(price.gst_registered, registered)
      assert.equal(price.gst_source, 'shop')
    }
    await preview('1338.93', true)
    await page.reload()
    await page.getByRole('tab', { name: 'Pricing & tax', exact: true }).click()
    await margin.waitFor()
    assert.equal(await margin.inputValue(), '12.345', 'Persisted three-decimal margin survives reload')
    await page.getByLabel(/Composition scheme/).check()
    const composition = await saveSettings()
    assert.equal(composition.gst_scheme, 'composition')
    assert.equal(composition.gst_registered, false)
    await preview('1336.91', false)
    await page.reload()
    await page.getByRole('tab', { name: 'Pricing & tax', exact: true }).click()
    await margin.waitFor()
    assert.equal(await margin.inputValue(), '12.345')
    assert.equal(await page.getByLabel(/Composition scheme/).isChecked(), true)
    if (process.env.STORELY_ARTIFACT_DIR) {
      fs.mkdirSync(process.env.STORELY_ARTIFACT_DIR, { recursive: true })
      await page.screenshot({ path: `${process.env.STORELY_ARTIFACT_DIR}/gst-pricing-settings.png`, fullPage: true })
    }
    process.stdout.write('PASS invalid defaults no PATCH and visible focus; exact 3dp guarded save/reload; authoritative regular1338.93 and composition1336.91 formula previews\n')
  } finally { await browser.close() }
})().catch(error => { process.stderr.write(String(error) + '\n'); process.exitCode = 1 })
