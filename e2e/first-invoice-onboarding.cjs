// Coordinator-owned fresh paid owner fixture with no products/invoices; cleanup is external.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const origin = process.env.STORELY_WEB_ORIGIN || 'http://127.0.0.1:5173'
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw new Error('Localhost origin required')
if (!process.env.STORELY_FIXTURE) throw new Error('Run-owned empty shop fixture required')
const fixture = JSON.parse(fs.readFileSync(process.env.STORELY_FIXTURE, 'utf8'))
;(async () => {
  const browser = await chromium.launch({ ...(process.env.CHROME_EXECUTABLE ? { executablePath: process.env.CHROME_EXECUTABLE } : {}) })
  const context = await browser.newContext({ ignoreHTTPSErrors: true })
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  page.on('dialog', dialog => dialog.accept())
  try {
    const login = await context.request.post(origin + '/v1/auth/login', { data: { email: fixture.email, password: fixture.password, client: 'mobile' }, headers: { 'X-Requested-With': 'storely-web' } })
    assert.ok(login.ok(), 'Fixture authentication')
    const headers = { authorization: `Bearer ${(await login.json()).access_token}` }
    const base = `/v1/shops/${fixture.shop_id}`
    async function get(path) { const result = await context.request.get(origin + path, { headers }); assert.ok(result.ok()); return result.json() }
    assert.equal((await get(base + '/products?limit=1')).total, 0, 'Fresh catalog required')
    assert.equal((await get(base + '/bills?kind=invoice&cancelled=false&limit=1')).total, 0)
    assert.equal((await get(base + '/bills?kind=invoice&cancelled=true&limit=1')).total, 0)
    let failProgress = true
    await page.route(`**/v1/shops/${fixture.shop_id}/bills?*`, async route => {
      const url = new URL(route.request().url())
      if (route.request().method() === 'GET' && url.searchParams.get('kind') === 'invoice' && url.searchParams.get('cancelled') === 'false' && failProgress) {
        return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'unavailable', message: 'Injected progress outage' } }) })
      }
      return route.continue()
    })
    await page.goto(origin + '/login')
    await page.getByLabel('Email', { exact: true }).fill(fixture.email)
    await page.getByLabel('Password', { exact: true }).fill(fixture.password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await page.getByRole('button', { name: 'Retry setup progress', exact: true }).waitFor()
    failProgress = false
    await page.getByRole('button', { name: 'Retry setup progress', exact: true }).click()
    const addFirst = page.getByRole('link', { name: 'Add your first product', exact: true })
    await addFirst.waitFor()
    assert.equal(await page.getByRole('link', { name: 'Create your first invoice', exact: true }).count(), 0)
    await addFirst.click()
    const editor = page.getByRole('dialog', { name: 'Add product', exact: true })
    const name = `First invoice rice ${fixture.run.slice(0, 8)}`
    await editor.getByLabel('Product name', { exact: true }).fill(name)
    await editor.getByLabel('Selling price (₹)', { exact: true }).fill('118')
    await editor.getByLabel('Opening stock', { exact: true }).fill('10')
    const productResponse = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === base + '/products')
    await editor.getByRole('button', { name: 'Add product', exact: true }).click()
    const created = await productResponse
    assert.ok(created.ok())
    const product = (await created.json()).product
    assert.equal(Number(product.quantity), 10)
    await page.getByRole('button', { name: 'Close details', exact: true }).click()
    async function dashboard() { await page.getByRole('navigation', { name: 'Main', exact: true }).getByRole('link', { name: 'Dashboard', exact: true }).click() }
    await dashboard()
    const createFirst = page.getByRole('link', { name: 'Create your first invoice', exact: true })
    await createFirst.waitFor()
    assert.equal(await addFirst.count(), 0, 'A product advances rather than completes guidance')
    await createFirst.click()
    const scan = page.getByLabel('Scan barcode or search products', { exact: true })
    await scan.fill(product.barcode || product.product_code || product.name)
    await scan.press('Enter')
    const quantity = page.getByLabel(`Quantity for ${product.name}`, { exact: true })
    await quantity.waitFor()
    await page.waitForFunction(() => { const button = document.querySelector('.checkout-submit button'); return button && !button.disabled && button.textContent.includes('118.00') })
    const invalidRequests = []
    page.on('request', request => {
      if (request.method() === 'POST' && /\/bills(?:\/preview)?$/.test(new URL(request.url()).pathname) && request.postData()?.includes('1.2345')) invalidRequests.push(request.url())
    })
    await quantity.fill('1.2345')
    assert.equal(await page.getByRole('button', { name: /^Create invoice/ }).isDisabled(), true)
    await page.reload()
    await quantity.waitFor()
    assert.equal(await quantity.inputValue(), '1.2345')
    assert.equal(await page.getByRole('button', { name: /^Create invoice/ }).isDisabled(), true)
    assert.deepEqual(invalidRequests, [])
    await quantity.fill('1.0000')
    await page.waitForFunction(() => { const button = document.querySelector('.checkout-submit button'); return button && !button.disabled && button.textContent.includes('118.00') })
    await page.getByLabel('Part paid', { exact: true }).check()
    const amount = page.getByLabel('Paid now (₹)', { exact: true })
    await amount.fill('50')
    await page.getByRole('button', { name: 'Hold invoice', exact: true }).click()
    await page.getByRole('region', { name: 'Held invoices', exact: true }).waitFor()
    await dashboard()
    await createFirst.waitFor()
    assert.equal((await get(base + '/bills?kind=invoice&cancelled=false&limit=1')).total, 0, 'Held work does not complete first invoice')
    await createFirst.click()
    await page.getByRole('button', { name: 'Resume held invoice', exact: true }).click()
    await amount.waitFor()
    assert.equal(await amount.inputValue(), '50')
    await page.reload()
    await amount.waitFor()
    assert.equal(await amount.inputValue(), '50')
    assert.equal(Number(await quantity.inputValue()), 1)
    await dashboard()
    await createFirst.waitFor()
    await createFirst.click()
    await amount.waitFor()
    await page.getByLabel('Part paid', { exact: true }).check()
    await amount.fill('50')
    await page.getByLabel('Keep this balance unassigned', { exact: true }).check()
    const writes = []
    let committed
    await page.route(`**/v1/shops/${fixture.shop_id}/bills`, async route => {
      if (route.request().method() !== 'POST') return route.continue()
      const request = route.request()
      writes.push({ key: request.headers()['idempotency-key'], body: request.postDataJSON() })
      if (writes.length === 1) {
        const response = await route.fetch()
        assert.ok(response.ok(), 'First invoice actually commits')
        committed = await response.json()
        return route.abort('failed')
      }
      return route.continue()
    })
    await page.getByRole('button', { name: /^Create invoice/ }).click()
    await page.getByRole('button', { name: 'Retry saving invoice', exact: true }).waitFor()
    await page.reload()
    assert.equal(await quantity.isDisabled(), true)
    await page.getByRole('button', { name: 'Retry saving invoice', exact: true }).click()
    await page.getByRole('heading', { name: 'Invoice saved', exact: true }).waitFor()
    assert.equal(writes.length, 2)
    assert.deepEqual(writes[1], writes[0], 'Unconfirmed retry uses identical operation')
    assert.equal(committed.bill.total_amount, '118.00')
    assert.equal(committed.bill.paid_amount, '50.00')
    assert.equal(committed.bill.balance_due, '68.00')
    const saved = await get(base + '/bills/' + committed.bill.uuid)
    assert.equal(saved.bill.uuid, committed.bill.uuid)
    assert.equal(saved.items[0].product_uuid, product.uuid)
    assert.equal(Number((await get(base + '/products/' + product.uuid)).product.quantity), 9, 'Stock reduced once')
    if (process.env.STORELY_ARTIFACT_DIR) {
      fs.mkdirSync(process.env.STORELY_ARTIFACT_DIR, { recursive: true })
      await page.screenshot({ path: `${process.env.STORELY_ARTIFACT_DIR}/first-invoice-completion.png`, fullPage: true })
    }
    await dashboard()
    await page.getByRole('region', { name: 'Setup progress', exact: true }).waitFor({ state: 'hidden' })
    assert.equal(await createFirst.count(), 0)
    assert.equal(await page.getByRole('heading', { name: 'Get your shop ready', exact: true }).count(), 0)
    await page.goto(origin + '/billing/' + committed.bill.uuid)
    await page.getByText('More actions', { exact: false }).click()
    await page.getByRole('button', { name: 'Void invoice', exact: true }).click()
    const voiding = page.getByRole('dialog', { name: 'Void invoice', exact: true })
    await voiding.getByLabel('Reason for voiding', { exact: true }).fill('Isolated onboarding acceptance')
    const cancelled = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith('/cancel'))
    await voiding.getByRole('button', { name: 'Void invoice', exact: true }).click()
    assert.ok((await cancelled).ok())
    await page.goto(origin + '/')
    await page.getByRole('region', { name: 'Setup progress', exact: true }).waitFor({ state: 'hidden' })
    assert.equal(await createFirst.count(), 0, 'Voided original still completes milestone')
    assert.equal((await get(base + '/bills?kind=invoice&cancelled=false&limit=1')).total, 0)
    const cancelledInvoices = await get(base + '/bills?kind=invoice&cancelled=true&limit=1')
    assert.equal(cancelledInvoices.total, 1)
    assert.equal(cancelledInvoices.items[0].uuid, committed.bill.uuid)
    process.stdout.write('PASS fresh owner product→first invoice guidance, progress retry, held/reloaded draft, real118/50/68 invoice, lost-ack exact retry/stock9, and cancelled-original completion\n')
  } finally { await browser.close() }
})().catch(error => { process.stderr.write(String(error) + '\n'); process.exitCode = 1 })
